"""Optional bridge to Sage (passagemath) for two things PARI alone cannot do:

1. ``prove_bsd``: Sage's ``EllipticCurve.prove_BSD`` — for curves of analytic rank ≤ 1 it
   *proves* the BSD formula at all primes except those it returns, using Kolyvagin's bound
   (Heegner index), Kato's bound, 2-descent at p = 2 and the refinements of
   Cha 2005, Jetchev 2008, Lawson–Wuthrich 2015, Stein–Wuthrich 2013 and
   Grigorov–Jorza–Patrikis–Stein–Tarniţă 2009.  The output "[]" means: the full BSD
   formula is a theorem for this curve (modulo the correctness of the implementation).
   The proof sketch printed by Sage (verbosity=2) is captured and stored.

2. ``provable_saturation``: Sage's ``EllipticCurve.saturation`` computes a provable lower
   bound for the canonical height (Cremona–Siksek / Thomas) and hence a provable bound for
   the index of the subgroup generated by the given points, then saturates at every prime up
   to that bound.  This removes the "saturated only at primes < 1000" caveat of ``descent.py``.

Sage is imported lazily; if it is unavailable every function raises ``SageUnavailable``.
"""
from __future__ import annotations

import contextlib
import io
import signal
from fractions import Fraction


class SageUnavailable(RuntimeError):
    pass


def _sage():
    try:
        import sage.all as S  # noqa: WPS433
    except Exception as exc:  # pragma: no cover
        raise SageUnavailable(str(exc)) from exc
    return S


class _Timeout(Exception):
    pass


@contextlib.contextmanager
def _alarm(seconds):
    """Python-level alarm (works for the pure-Python parts of Sage; cysignals handles C parts)."""
    if not seconds:
        yield
        return

    def handler(signum, frame):
        raise _Timeout()
    old = signal.signal(signal.SIGALRM, handler)
    signal.setitimer(signal.ITIMER_REAL, seconds)
    try:
        yield
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, old)


def sage_curve(ainvs):
    S = _sage()
    return S.EllipticCurve(S.QQ, [int(a) for a in ainvs])


def prove_bsd(ainvs, timeout: float | None = 600.0, secs_hi: int = 20) -> dict:
    """Run Sage's prove_BSD. Returns dict(primes_unproven=[...], proof_sketch=str, status=str)."""
    E = sage_curve(ainvs)
    buf = io.StringIO()
    try:
        with _alarm(timeout), contextlib.redirect_stdout(buf):
            res = E.prove_BSD(verbosity=2, two_desc="pari", secs_hi=secs_hi)
    except _Timeout:
        return dict(primes_unproven=None, proof_sketch=buf.getvalue(), status=f"timeout after {timeout}s")
    except Exception as exc:  # noqa: BLE001
        msg = str(exc)
        if "rank" in msg.lower() and "analytic" in msg.lower() or "proof=True" in msg:
            return dict(primes_unproven=None, proof_sketch=buf.getvalue(), status=f"not applicable: {msg[:120]}")
        return dict(primes_unproven=None, proof_sketch=buf.getvalue(), status=f"error: {type(exc).__name__}: {msg[:160]}")
    try:
        primes = sorted(int(p) for p in res)
        status = "full BSD formula proven at all primes" if not primes else f"proven at all primes except {primes}"
    except TypeError:  # Sage returns the set of all primes for rank >= 2
        primes = None
        status = "not applicable (analytic rank ≥ 2): nothing proven"
    return dict(primes_unproven=primes, proof_sketch=buf.getvalue().strip(), status=status)


def provable_saturation(ainvs, gens, timeout: float | None = 600.0) -> dict:
    """Provably saturate the subgroup generated by `gens` (affine rational points)."""
    S = _sage()
    E = sage_curve(ainvs)
    P = [E([S.QQ(Fraction(x)), S.QQ(Fraction(y))]) for x, y in gens]
    if not P:
        return dict(gens=[], index=1, regulator=1.0, status="rank 0")
    try:
        with _alarm(timeout):
            sat, index, reg = E.saturation(P)
            hb = float(E.height_function().min_gr(0.01, 5)) if hasattr(E, "height_function") else None
    except _Timeout:
        return dict(gens=None, index=None, regulator=None, status=f"timeout after {timeout}s")
    out_gens = [[str(S.QQ(Q[0])), str(S.QQ(Q[1]))] for Q in sat]
    return dict(gens=out_gens, index=int(index), regulator=float(reg), height_lower_bound=hb,
                status="provably saturated (Sage: Cremona–Siksek height bound + p-saturation up to the index bound)")
