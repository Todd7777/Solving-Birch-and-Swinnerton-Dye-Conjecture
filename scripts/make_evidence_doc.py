#!/usr/bin/env python3
"""Build docs/05-numerical-evidence.md from the JSONL results in results/."""
from __future__ import annotations

import glob
import json
import os
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from bsd.report import read_jsonl, records_table, curve_section  # noqa: E402


def sweep_stats(recs):
    n = len(recs)
    ranks = Counter(r["analytic"]["analytic_rank"] for r in recs)
    shas = Counter(r["sha_an_int"] for r in recs if r["sha_an_int"] is not None)
    nonsq = [r["label"] for r in recs if r["sha_is_square"] is False]
    errs = [r for r in recs if r.get("errors")]
    mism = [r["label"] for r in recs if r.get("cremona") and r["cremona"].get("mismatches")]
    rig = Counter("exact" if r["analytic"].get("rigorous_order_exact") else "lower bound only" for r in recs)
    maxrel = max((r["sha_rel_err"] or 0.0) for r in recs) if recs else 0.0
    descent_exact = sum(1 for r in recs if r["descent"].get("rank_lower") == r["descent"].get("rank_upper"))
    sha2 = sum(1 for r in recs if (r["descent"].get("sha2_mod_4_rank") or 0) > 0)
    # p-part ledger stats for rank <= 1
    proven_all_odd = 0
    led = 0
    for r in recs:
        if r["analytic"]["analytic_rank"] <= 1 and r.get("p_part"):
            led += 1
            if all(p["status"] == "proven" for p in r["p_part"] if p["p"] >= 5):
                proven_all_odd += 1
    sage_full = sage_part = sage_na = 0
    unproven = Counter()
    sat_fixed = 0
    for r in recs:
        sg = r.get("sage") or {}
        pb = sg.get("prove_bsd")
        if pb:
            if pb.get("primes_unproven") == []:
                sage_full += 1
            elif pb.get("primes_unproven"):
                sage_part += 1
                for q in pb["primes_unproven"]:
                    unproven[q] += 1
            else:
                sage_na += 1
        st = sg.get("saturation")
        if st and st.get("index") not in (None, 1):
            sat_fixed += 1
    return dict(n=n, ranks=ranks, shas=shas, nonsq=nonsq, errs=errs, mism=mism, rig=rig, maxrel=maxrel,
                descent_exact=descent_exact, sha2=sha2, led=led, proven_all_odd=proven_all_odd,
                sage_full=sage_full, sage_part=sage_part, sage_na=sage_na, unproven=unproven, sat_fixed=sat_fixed)


def fmt_counter(c, key=lambda kv: kv[0]):
    return ", ".join(f"{k}: {v}" for k, v in sorted(c.items(), key=key))


def main():
    out = []
    out.append("# 5. Numerical evidence produced by this repository\n")
    out.append("All numbers below were computed by `python -m bsd …` with PARI/GP 2.17 (cypari2) in this repository, "
               "and compared against John Cremona's independently computed tables (eclib/mwrank). "
               "Raw outputs are in `results/*.jsonl`; this file is generated by `scripts/make_evidence_doc.py`.\n")
    out.append("**Reading guide.** \"$\\#Ш_{\\mathrm{an}}$ is a square\" and \"agrees with Cremona\" are *evidence* for formula (II). "
               "\"THEOREM\" lines are theorems. For rank $\\ge2$ curves the only rigorous outputs are the 2-descent rank bounds, "
               "the exact vanishing $L(E,1)=0$, and the prime-by-prime finiteness of $Ш[p^\\infty]$. "
               "Statements that are *proved* (certified computations), including rank $=$ analytic rank for every "
               "curve of conductor $<20000$, are collected in file 06.\n")

    # sweeps
    all_sweeps = sorted(glob.glob(os.path.join(ROOT, "results", "sweep_*.jsonl")))
    sweeps = [p for p in all_sweeps if not p.endswith("_sage.jsonl")]
    sage_sweeps = [p for p in all_sweeps if p.endswith("_sage.jsonl")]
    if sweeps:
        out.append("## 5.1 Systematic sweeps over Cremona's database\n")
        out.append("For every curve: invariants, analytic rank and leading term, exact $L(E,1)/\\Omega^+$ by modular symbols, "
                   "an independent 2-descent (PARI `ellrank`, seeded with Cremona's generators, which it re-verifies), "
                   "saturation at all primes $<1000$, regulator, $\\#Ш_{\\mathrm{an}}$, and the theorem ledger.\n")
        out.append("| conductor range | curves | analytic ranks | $\\#Ш_{\\mathrm{an}}$ values | non-square $\\#Ш_{\\mathrm{an}}$ | max rel. error of $\\#Ш_{\\mathrm{an}}$ | 2-descent pins rank | $Ш[2]\\ne0$ detected | mismatches with Cremona | errors |")
        out.append("|---|---|---|---|---|---|---|---|---|---|")
        allrecs = []
        for path in sweeps:
            recs = read_jsonl(path)
            allrecs += recs
            s = sweep_stats(recs)
            tag = os.path.basename(path).replace("sweep_", "").replace(".jsonl", "").replace("_", "–")
            out.append(f"| {tag} | {s['n']} | {fmt_counter(s['ranks'])} | {fmt_counter(s['shas'])} | {len(s['nonsq'])} | {s['maxrel']:.1e} | "
                       f"{s['descent_exact']} | {s['sha2']} | {len(s['mism'])} | {len(s['errs'])} |")
        s = sweep_stats(allrecs)
        out.append("")
        out.append(f"**Totals: {s['n']} curves.** Analytic ranks: {fmt_counter(s['ranks'])}. $\\#Ш_{{\\mathrm{{an}}}}$: {fmt_counter(s['shas'])}. "
                   f"Non-square: {len(s['nonsq'])}. Mismatches with Cremona's tables: {len(s['mism'])}. Errors: {len(s['errs'])}.")
        out.append(f"Rigorous status of $\\operatorname{{ord}}_{{s=1}}L$: {fmt_counter(s['rig'])}.")
        out.append(f"Curves of analytic rank $\\le1$ for which the mechanised theorems prove the $p$-part of (II) at **every** prime $p\\ge5$ in the ledger: "
                   f"{s['proven_all_odd']} of {s['led']}.")
        if s["errs"]:
            out.append("\nCurves with warnings:\n")
            for r in s["errs"][:50]:
                out.append(f"- {r['label']}: {' | '.join(r['errors'])}")
        out.append("")
    for path in sage_sweeps:
        recs = read_jsonl(path)
        s = sweep_stats(recs)
        tag = os.path.basename(path).replace("sweep_", "").replace("_sage.jsonl", "").replace("_", "–")
        out.append(f"### Proofs of the full formula with Sage, conductor range {tag} ({s['n']} curves)\n")
        out.append("Same pipeline, plus Sage's provable saturation of every Mordell–Weil basis and, for analytic rank ≤ 1, Sage's `prove_BSD`.\n")
        if s["sage_full"] or s["sage_part"]:
            out.append(f"**Sage `prove_BSD` (Kolyvagin + Kato bounds, 2-descent, Cha/Jetchev/Lawson–Wuthrich/Stein–Wuthrich refinements):** "
                       f"full formula (II) proven at every prime for **{s['sage_full']}** curves; proven at all but the listed primes for {s['sage_part']} curves "
                       f"(unproven primes, with multiplicity: {fmt_counter(s['unproven'])}); not applicable/failed for {s['sage_na']}. "
                       f"Provable saturation changed a PARI basis in {s['sat_fixed']} cases.")
            partial = [r for r in recs if (r.get("sage") or {}).get("prove_bsd", {}).get("primes_unproven")]
            if partial:
                out.append("\nCurves where `prove_BSD` leaves primes open (label: primes): " +
                           ", ".join(f"{r['label']}: {r['sage']['prove_bsd']['primes_unproven']}" for r in partial[:200]) +
                           (" …" if len(partial) > 200 else ""))
        if s["errs"]:
            out.append("\nCurves with warnings:\n")
            for r in s["errs"][:50]:
                out.append(f"- {r['label']}: {' | '.join(r['errors'])}")
        out.append("")

    # curated
    cur = os.path.join(ROOT, "results", "curated.jsonl")
    if os.path.exists(cur):
        recs = read_jsonl(cur)
        out.append("## 5.2 Curated curves (every feature of the conjecture, ranks 0–7)\n")
        out.append(records_table(recs))
        out.append("")
        out.append("### Finiteness of $Ш[p^\\infty]$ for curves of rank $\\ge2$ (Kato + $p$-adic $L$-functions)\n")
        out.append("For each good ordinary odd prime $p$ in the range computed, PARI certifies an upper bound $r_p$ for $\\operatorname{ord}_{T=0}L_p(E,T)$; "
                   "when $r_p$ equals the number of independent points found, Kato's theorem and Mazur's control theorem give $\\operatorname{corank}\\operatorname{Sel}_{p^\\infty}=r$, "
                   "i.e. $Ш[p^\\infty]$ is finite (see `bsd/theorems.py`). The column $L_p/R_p$ is the $p$-adic BSD quotient, conjecturally $\\#Ш$.\n")
        out.append("| curve | rank | primes $p$ with $Ш[p^\\infty]$ proven finite | primes not certified | $L_p^{(r)}(0)/r!\\,/\\,R_p$ (p-adic BSD) |")
        out.append("|---|---|---|---|---|")
        for r in recs:
            if r["analytic"]["analytic_rank"] >= 2 and r.get("padic"):
                fin = [str(d["p"]) for d in r["padic"] if d.get("kato", {}).get("sha_p_finite")]
                notf = [str(d["p"]) for d in r["padic"] if not d.get("kato", {}).get("sha_p_finite")]
                units = "; ".join(f"{d['p']}: {d['sha_p']}" for d in r["padic"][:6] if d.get("sha_p"))
                out.append(f"| {r['label']} | {r['analytic']['analytic_rank']} | {', '.join(fin) or '—'} | {', '.join(notf) or '—'} | {units} … |")
        out.append("")
        out.append("### Curve-by-curve detail\n")
        for r in recs:
            if r.get("note"):
                out.append(f"*{r['note']}*\n")
            out.append(curve_section(r))

    # heuristic
    heur = os.path.join(ROOT, "results", "heuristic.json")
    if os.path.exists(heur):
        H = json.load(open(heur))
        out.append("## 5.3 The 1965 heuristic\n")
        out.append("Least-squares slope of $\\log\\prod_{p\\le X,\\,p\\nmid N}N_p/p$ against $\\log\\log X$ (should be $\\approx$ rank):\n")
        out.append("| curve | rank | fitted exponent |\n|---|---|---|")
        for h in H:
            out.append(f"| {h['label']} | {h['rank']} | {h['fitted_exponent']:.3f} |")
        out.append("\n![BSD heuristic](../results/heuristic.png)\n")

    with open(os.path.join(ROOT, "docs", "05-numerical-evidence.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote docs/05-numerical-evidence.md")


if __name__ == "__main__":
    main()
